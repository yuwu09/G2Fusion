class DiTBlock(nn.Module):
    """
    A DiT block with adaptive layer norm zero (adaLN-Zero) conditioning.
    """
    def __init__(self, hidden_size, num_heads, mlp_ratio=4.0, **block_kwargs):
        super().__init__()
        self.norm1 = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        self.attn = Attention(hidden_size, num_heads=num_heads, qkv_bias=True, **block_kwargs)
        self.norm2 = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        mlp_hidden_dim = int(hidden_size * mlp_ratio)
        approx_gelu = lambda: nn.GELU(approximate="tanh")
        self.mlp = Mlp(in_features=hidden_size, hidden_features=mlp_hidden_dim, act_layer=approx_gelu, drop=0)
        self.adaLN_modulation = nn.Sequential(
            nn.SiLU(),
            nn.Linear(hidden_size, 6 * hidden_size, bias=True)
        )

    def forward(self, x, c):
        shift_msa, scale_msa, gate_msa, shift_mlp, scale_mlp, gate_mlp = self.adaLN_modulation(c).chunk(6, dim=1)
        x = x + gate_msa.unsqueeze(1) * self.attn(modulate(self.norm1(x), shift_msa, scale_msa))
        x = x + gate_mlp.unsqueeze(1) * self.mlp(modulate(self.norm2(x), shift_mlp, scale_mlp))
        return x


class FinalLayer(nn.Module):
    """
    The final layer of DiT.
    """
    def __init__(self, hidden_size, patch_size, out_channels):
        super().__init__()
        self.norm_final = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        self.linear = nn.Linear(hidden_size, patch_size * patch_size * out_channels, bias=True)
        self.adaLN_modulation = nn.Sequential(
            nn.SiLU(),
            nn.Linear(hidden_size, 2 * hidden_size, bias=True)
        )

    def forward(self, x, c):
        shift, scale = self.adaLN_modulation(c).chunk(2, dim=1)
        x = modulate(self.norm_final(x), shift, scale)
        x = self.linear(x)
        return x


class DiT(nn.Module):
    """
    Diffusion model with a Transformer backbone.
    """
    def __init__(
        self,
        input_size=16,
        patch_size=2,
        in_channels=8,
        hidden_size=1152,
        depth=28,
        num_heads=16,
        mlp_ratio=4.0,
        learn_sigma=True,
    ):
        super().__init__()
        self.learn_sigma = learn_sigma
        self.in_channels = in_channels
        self.out_channels = in_channels * 2 if learn_sigma else in_channels
        self.patch_size = patch_size
        self.num_heads = num_heads
        self.hidden_size = hidden_size
        self.x_embedder = PatchEmbed(input_size, patch_size, in_channels*3, hidden_size, bias=True)
        self.t_embedder = TimestepEmbedder(hidden_size)
        patches_per_side = input_size // patch_size
        num_patches = patches_per_side * patches_per_side
        self.patches_per_side = patches_per_side
        self.num_patches = num_patches 
        # Will use fixed sin-cos embedding:
        self.pos_embed = nn.Parameter(torch.zeros(1, self.num_patches, hidden_size), requires_grad=False)

        self.blocks = nn.ModuleList([
            DiTBlock(hidden_size, num_heads, mlp_ratio=mlp_ratio) for _ in range(depth)
        ])
        self.final_layer = FinalLayer(hidden_size, patch_size, self.out_channels)
        self.initialize_weights()

    def initialize_weights(self):
        # Initialize transformer layers:
        def _basic_init(module):
            if isinstance(module, nn.Linear):
                torch.nn.init.xavier_uniform_(module.weight)
                if module.bias is not None:
                    nn.init.constant_(module.bias, 0)
        self.apply(_basic_init)

        # Initialize (and freeze) pos_embed by sin-cos embedding:
        pos_embed = get_2d_sincos_pos_embed(self.pos_embed.shape[-1], int(self.num_patches ** 0.5))
        self.pos_embed.data.copy_(torch.from_numpy(pos_embed).float().unsqueeze(0))

        # Initialize patch_embed like nn.Linear (instead of nn.Conv2d):
        w = self.x_embedder.proj.weight.data
        nn.init.xavier_uniform_(w.view([w.shape[0], -1]))
        nn.init.constant_(self.x_embedder.proj.bias, 0)

        # Initialize label embedding table:
        # nn.init.normal_(self.y_embedder.embedding_table.weight, std=0.02)

        # Initialize timestep embedding MLP:
        nn.init.normal_(self.t_embedder.mlp[0].weight, std=0.02)
        nn.init.normal_(self.t_embedder.mlp[2].weight, std=0.02)

        # Zero-out adaLN modulation layers in DiT blocks:
        for block in self.blocks:
            nn.init.constant_(block.adaLN_modulation[-1].weight, 0)
            nn.init.constant_(block.adaLN_modulation[-1].bias, 0)

        # Zero-out output layers:
        nn.init.constant_(self.final_layer.adaLN_modulation[-1].weight, 0)
        nn.init.constant_(self.final_layer.adaLN_modulation[-1].bias, 0)
        nn.init.constant_(self.final_layer.linear.weight, 0)
        nn.init.constant_(self.final_layer.linear.bias, 0)


    def unpatchify(self, x, h_patches, w_patches):
        """
        x: (N, T, patch_size**2 * C)
        h_patches: The number of patches in the height dimension
        w_patches: The number of patches in the width dimension
        imgs: (N, C, H, W)
        """
        c = self.out_channels
        p = self.patch_size
        h, w = h_patches, w_patches
        assert h * w == x.shape[1]

        x = x.reshape(shape=(x.shape[0], h, w, p, p, c))
        x = torch.einsum('nhwpqc->nchpwq', x)
        imgs = x.reshape(shape=(x.shape[0], c, h * p, w * p))
        return imgs

    def ckpt_wrapper(self, module):
        def ckpt_forward(*inputs):
            return module(*inputs)
        return ckpt_forward
    
    ### MODIFIED: The forward pass now handles dynamic positional embedding interpolation
    def forward(self, x, t, cond_img1, cond_img2):
        """
        x: Latent noise [N, in_channels, H, W]
        t: Timesteps (N,)
        cond_img1, cond_img2: Conditional latent images [N, in_channels, H, W]
        """
        latent_h, latent_w = x.shape[-2:]
        
        # Concatenate inputs
        x = torch.cat([x, cond_img1, cond_img2], dim=1)
        
        # Embed patches
        x = self.x_embedder(x) # (N, T, D)
        
        # Get the new patch grid size
        num_patches_h = latent_h // self.patch_size
        num_patches_w = latent_w // self.patch_size

        # Interpolate positional embedding if needed
        if self.pos_embed.shape[1] != x.shape[1]:
            # This is the same logic from the main script, now moved inside the model
            # for cleaner execution.
            pos_embed_trained = self.pos_embed
            num_patches_trained_side = self.patches_per_side
            pos_embed_trained_grid = pos_embed_trained.transpose(1, 2).view(
                1, self.hidden_size, num_patches_trained_side, num_patches_trained_side
            )
            
            pos_embed_interpolated_grid = F.interpolate(
                pos_embed_trained_grid,
                size=(num_patches_h, num_patches_w),
                mode='bicubic',
                align_corners=False
            )
            
            pos_embed_interpolated = pos_embed_interpolated_grid.flatten(2).transpose(1, 2)
            current_pos_embed = pos_embed_interpolated
        else:
            # Input size matches training size, no interpolation needed
            current_pos_embed = self.pos_embed

        x = x + current_pos_embed
        t = self.t_embedder(t)
        c = t # (N, D)
        
        for block in self.blocks:
            x = torch.utils.checkpoint.checkpoint(self.ckpt_wrapper(block), x, c)
            
        x = self.final_layer(x, c)
        
        ### MODIFIED: Pass the patch dimensions to the updated unpatchify method
        x = self.unpatchify(x, num_patches_h, num_patches_w)
        return x

    def forward_with_cfg(self, x, t, cond_img1,cond_img2, cfg_scale):
        """
        Forward pass with classifier-free guidance (CFG).
        Forward pass of DiT, but also batches the unconditional forward pass for classifier-free guidance.
        """
        # https://github.com/openai/glide-text2im/blob/main/notebooks/text2im.ipynb
        half = x[: len(x) // 2]
        half_cond1 = cond_img1[: len(cond_img1) // 2]
        half_cond2 = cond_img2[: len(cond_img2) // 2]
        combined = torch.cat([half, half], dim=0)
        combined_cond1 = torch.cat([half_cond1, half_cond1], dim=0)
        combined_cond2 = torch.cat([half_cond2, half_cond2], dim=0)
        model_out = self.forward(combined, t, cond_img1=combined_cond1,cond_img2=combined_cond2)  # [2N, out_channels, H, W]
        # For exact reproducibility reasons, we apply classifier-free guidance on only
        # three channels by default. The standard approach to cfg applies it to all channels.
        # This can be done by uncommenting the following line and commenting-out the line following that.
        # eps, rest = model_out[:, :self.in_channels], model_out[:, self.in_channels:]
        eps, rest = model_out[:, :3], model_out[:, 3:]
        cond_eps, uncond_eps = torch.split(eps, len(eps) // 2, dim=0)
        half_eps = uncond_eps + cfg_scale * (cond_eps - uncond_eps)
        eps = torch.cat([half_eps, half_eps], dim=0)
        return torch.cat([eps, rest], dim=1)


